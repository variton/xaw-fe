export function themeStyle(theme: Theme): string {
  const keys = [
    "bg",
    "panel",
    "panel-2",
    "text",
    "muted",
    "border",
    "accent",
    "heading",
    "hover",
    "secondary",
    "bad",
  ];
  return (
    keys.map((key, i) => `--theme-${key}:${palettes[theme][i]}`).join(";") +
    `;--theme-scheme:${theme === "light" ? "light" : "dark"};color-scheme:${theme === "light" ? "light" : "dark"}`
  );
}
